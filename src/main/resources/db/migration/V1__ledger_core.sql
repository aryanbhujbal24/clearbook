-- Clearbook core ledger.
--
-- Two decisions drive this schema, and everything else follows from them.
--
-- 1. Balances are DERIVED, never stored and mutated. The journal is the only
--    source of truth; a balance is a fold over it. That is what makes every
--    number on a statement reconstructable and auditable — you can always ask
--    "which entries produced this figure?" and get an exact answer.
--
-- 2. An entry must balance PER ASSET, not overall. A trade moves rupees and
--    shares at the same time, and those cannot sum together meaningfully. So
--    the zero-sum rule is scoped to (entry, asset): the cash legs net to zero
--    in INR, and the stock legs net to zero in that symbol.
--
-- Both rules are enforced by the database rather than by application code, so
-- no future code path — including one nobody has written yet — can violate
-- them.

-- ---------------------------------------------------------------------------
-- accounts
-- ---------------------------------------------------------------------------

CREATE TABLE account (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            TEXT        NOT NULL UNIQUE,
    kind            TEXT        NOT NULL,
    owner_id        TEXT,
    -- Optimistic-locking token. Posting to an account bumps this, so two
    -- concurrent margin-checked postings to the same account collide and one
    -- is forced to retry against a balance it has re-read. Without it, both
    -- read the same pre-trade balance, both pass their margin check, and
    -- together they breach it — a write skew that leaves the ledger perfectly
    -- balanced and the account quietly undermargined.
    version         BIGINT      NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT account_kind_valid CHECK (kind IN (
        'CLIENT_CASH',
        'CLIENT_SECURITIES',
        'HOUSE_CASH',
        'SETTLEMENT_SUSPENSE',
        'BROKERAGE_INCOME',
        'TAX_PAYABLE',
        'EXCHANGE_FEES',
        -- Reserved, and deliberately unused today. Fees are computed per
        -- component and the charged total is defined as their sum, so a trade
        -- entry balances exactly and there is no residue to park. The account
        -- exists because pro-rata allocation of a block fill across several
        -- client accounts does produce one, and that is the next thing this
        -- ledger will need.
        'ROUNDING_RESIDUE'
    )),
    -- Client accounts belong to someone; house and income accounts do not.
    CONSTRAINT account_owner_consistent CHECK (
        (kind LIKE 'CLIENT%' AND owner_id IS NOT NULL)
        OR (kind NOT LIKE 'CLIENT%' AND owner_id IS NULL)
    )
);

CREATE INDEX account_owner_idx ON account (owner_id) WHERE owner_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- journal
-- ---------------------------------------------------------------------------

CREATE TABLE journal_entry (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind            TEXT        NOT NULL,
    -- The idempotency key. A trade that arrives twice — a Kafka redelivery, a
    -- client retry after a timeout — must post exactly once. This is a UNIQUE
    -- constraint rather than an application-level "have I seen this?" check,
    -- because the check-then-insert race is exactly what redelivery triggers.
    trade_id        TEXT        UNIQUE,
    business_date   DATE        NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    description     TEXT,

    CONSTRAINT journal_entry_kind_valid CHECK (kind IN (
        'TRADE', 'SETTLEMENT', 'FEE', 'ADJUSTMENT', 'OPENING_BALANCE'
    )),
    -- Trades carry an idempotency key; opening balances and adjustments are
    -- posted by hand and do not.
    CONSTRAINT journal_entry_trade_has_id CHECK (
        (kind = 'TRADE') = (trade_id IS NOT NULL)
    )
);

CREATE INDEX journal_entry_date_idx ON journal_entry (business_date, id);

CREATE TABLE journal_line (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id        BIGINT      NOT NULL REFERENCES journal_entry (id),
    account_id      BIGINT      NOT NULL REFERENCES account (id),
    -- 'INR' for cash, 'EQ:<SYMBOL>' for stock. Keeping both in one ledger is
    -- what lets a single entry describe a whole trade.
    asset           TEXT        NOT NULL,
    -- Signed. Paise for INR, whole shares for equity. Never a floating-point
    -- type: 0.1 + 0.2 != 0.3 is not an acceptable property for money.
    amount          BIGINT      NOT NULL,

    CONSTRAINT journal_line_amount_nonzero CHECK (amount <> 0),
    CONSTRAINT journal_line_asset_shape CHECK (asset ~ '^(INR|EQ:[A-Z0-9&_-]{1,24})$')
);

CREATE INDEX journal_line_entry_idx   ON journal_line (entry_id);
CREATE INDEX journal_line_balance_idx ON journal_line (account_id, asset, id);

-- ---------------------------------------------------------------------------
-- the zero-sum rule
-- ---------------------------------------------------------------------------

-- Enforced as a CONSTRAINT TRIGGER deferred to commit time, because the rule
-- is about the finished entry: the lines are inserted one at a time, and an
-- entry is necessarily unbalanced in between.
CREATE FUNCTION assert_entry_balances() RETURNS TRIGGER AS $$
DECLARE
    offending RECORD;
BEGIN
    SELECT asset, SUM(amount) AS total
      INTO offending
      FROM journal_line
     WHERE entry_id = COALESCE(NEW.entry_id, OLD.entry_id)
     GROUP BY asset
    HAVING SUM(amount) <> 0
     LIMIT 1;

    IF FOUND THEN
        RAISE EXCEPTION
            'journal entry % does not balance: asset % nets to %',
            COALESCE(NEW.entry_id, OLD.entry_id), offending.asset, offending.total
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER journal_line_balances
    AFTER INSERT OR UPDATE OR DELETE ON journal_line
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION assert_entry_balances();

-- ---------------------------------------------------------------------------
-- balance checkpoints
-- ---------------------------------------------------------------------------

-- Deriving a balance by summing every line an account has ever had is correct
-- but O(history), and a margin check runs on the critical path of every trade.
--
-- A checkpoint is a memo, not a second source of truth: balance = checkpoint
-- amount + the sum of lines after it. Delete every checkpoint and the system
-- still returns identical answers, only slower — which is the property that
-- keeps "balances are derived" honest, and which the test suite asserts.
--
-- Why checkpointing on a line id is safe here, when in general it is not:
-- identity values are handed out before commit, so two concurrent writers can
-- commit out of order. Line 101 becomes visible, a checkpoint is taken
-- "through 101", and line 100 commits afterwards — permanently invisible to
-- every future balance. That bug is real, and it is avoided only because
-- every posting bumps account.version, so postings to a single account cannot
-- commit concurrently: one of them fails the optimistic-lock check and
-- retries. Line ids are therefore gap-free in commit order *per account*,
-- which is exactly the scope a checkpoint covers.
--
-- Remove the version bump and this table silently starts losing money. The
-- two mechanisms are load-bearing together, not independently.
CREATE TABLE balance_checkpoint (
    account_id      BIGINT      NOT NULL REFERENCES account (id),
    asset           TEXT        NOT NULL,
    -- The checkpoint covers every line with id <= this value.
    through_line_id BIGINT      NOT NULL,
    amount          BIGINT      NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (account_id, asset)
);

-- ---------------------------------------------------------------------------
-- mark prices, for margin
-- ---------------------------------------------------------------------------

CREATE TABLE mark_price (
    symbol          TEXT        NOT NULL,
    business_date   DATE        NOT NULL,
    price           BIGINT      NOT NULL,  -- paise per share
    PRIMARY KEY (symbol, business_date),

    CONSTRAINT mark_price_positive CHECK (price > 0)
);
